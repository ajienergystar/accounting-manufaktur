CREATE TABLE purchase_requests (
    id              BIGINT       NOT NULL AUTO_INCREMENT,
    doc_no          VARCHAR(30)  NOT NULL,
    doc_date        DATE         NOT NULL,
    department_id   BIGINT,
    requested_by    VARCHAR(100) NOT NULL,
    needed_date     DATE,
    notes           VARCHAR(500),
    status          VARCHAR(12)  NOT NULL,
    approved_by     VARCHAR(100),
    approved_at     DATETIME(6),
    created_at      DATETIME(6)  NOT NULL,
    created_by      VARCHAR(100),
    updated_at      DATETIME(6),
    updated_by      VARCHAR(100),
    version         BIGINT       NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    UNIQUE KEY uk_pr_no (doc_no),
    CONSTRAINT fk_pr_dept FOREIGN KEY (department_id) REFERENCES departments (id),
    CONSTRAINT ck_pr_status CHECK (status IN ('DRAFT', 'SUBMITTED', 'APPROVED', 'REJECTED', 'ORDERED', 'CANCELLED'))
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_unicode_ci;

CREATE TABLE purchase_request_lines (
    id              BIGINT         NOT NULL AUTO_INCREMENT,
    request_id      BIGINT         NOT NULL,
    line_no         SMALLINT       NOT NULL,
    item_id         BIGINT         NOT NULL,
    qty             DECIMAL(19, 4) NOT NULL,
    note            VARCHAR(255),
    PRIMARY KEY (id),
    CONSTRAINT fk_prl_header FOREIGN KEY (request_id) REFERENCES purchase_requests (id) ON DELETE CASCADE,
    CONSTRAINT fk_prl_item FOREIGN KEY (item_id) REFERENCES items (id),
    CONSTRAINT ck_prl_qty CHECK (qty > 0)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_unicode_ci;

CREATE TABLE purchase_orders (
    id              BIGINT         NOT NULL AUTO_INCREMENT,
    doc_no          VARCHAR(30)    NOT NULL,
    doc_date        DATE           NOT NULL,
    supplier_id     BIGINT         NOT NULL,
    request_id      BIGINT,
    warehouse_id    BIGINT         NOT NULL,
    expected_date   DATE,
    tax_rate_id     BIGINT,
    tax_rate        DECIMAL(7, 4)  NOT NULL DEFAULT 0,
    subtotal        DECIMAL(19, 2) NOT NULL DEFAULT 0,
    discount_amount DECIMAL(19, 2) NOT NULL DEFAULT 0,
    tax_amount      DECIMAL(19, 2) NOT NULL DEFAULT 0,
    total           DECIMAL(19, 2) NOT NULL DEFAULT 0,
    notes           VARCHAR(500),
    status          VARCHAR(12)    NOT NULL,
    approved_by     VARCHAR(100),
    approved_at     DATETIME(6),
    created_at      DATETIME(6)    NOT NULL,
    created_by      VARCHAR(100),
    updated_at      DATETIME(6),
    updated_by      VARCHAR(100),
    version         BIGINT         NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    UNIQUE KEY uk_po_no (doc_no),
    KEY ix_po_supplier (supplier_id, status),
    CONSTRAINT fk_po_supplier FOREIGN KEY (supplier_id) REFERENCES suppliers (id),
    CONSTRAINT fk_po_request FOREIGN KEY (request_id) REFERENCES purchase_requests (id),
    CONSTRAINT fk_po_wh FOREIGN KEY (warehouse_id) REFERENCES warehouses (id),
    CONSTRAINT fk_po_tax FOREIGN KEY (tax_rate_id) REFERENCES tax_rates (id),
    CONSTRAINT ck_po_status CHECK (status IN ('DRAFT', 'APPROVED', 'PARTIAL', 'RECEIVED', 'CLOSED', 'CANCELLED'))
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_unicode_ci;

CREATE TABLE purchase_order_lines (
    id              BIGINT         NOT NULL AUTO_INCREMENT,
    order_id        BIGINT         NOT NULL,
    line_no         SMALLINT       NOT NULL,
    item_id         BIGINT         NOT NULL,
    description     VARCHAR(255),
    qty             DECIMAL(19, 4) NOT NULL,
    unit_price      DECIMAL(19, 4) NOT NULL,
    discount_pct    DECIMAL(7, 4)  NOT NULL DEFAULT 0,
    line_total      DECIMAL(19, 2) NOT NULL,
    qty_received    DECIMAL(19, 4) NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    CONSTRAINT fk_pol_header FOREIGN KEY (order_id) REFERENCES purchase_orders (id) ON DELETE CASCADE,
    CONSTRAINT fk_pol_item FOREIGN KEY (item_id) REFERENCES items (id),
    CONSTRAINT ck_pol_qty CHECK (qty > 0 AND qty_received >= 0),
    CONSTRAINT ck_pol_price CHECK (unit_price >= 0 AND discount_pct >= 0 AND discount_pct <= 100)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_unicode_ci;

CREATE TABLE goods_receipts (
    id              BIGINT         NOT NULL AUTO_INCREMENT,
    doc_no          VARCHAR(30)    NOT NULL,
    doc_date        DATE           NOT NULL,
    supplier_id     BIGINT         NOT NULL,
    order_id        BIGINT,
    warehouse_id    BIGINT         NOT NULL,
    delivery_note_no VARCHAR(50),
    freight_cost    DECIMAL(19, 2) NOT NULL DEFAULT 0,
    total_value     DECIMAL(19, 2) NOT NULL DEFAULT 0,
    notes           VARCHAR(500),
    status          VARCHAR(10)    NOT NULL,
    journal_id      BIGINT,
    created_at      DATETIME(6)    NOT NULL,
    created_by      VARCHAR(100),
    updated_at      DATETIME(6),
    updated_by      VARCHAR(100),
    version         BIGINT         NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    UNIQUE KEY uk_grn_no (doc_no),
    KEY ix_grn_supplier (supplier_id),
    CONSTRAINT fk_grn_supplier FOREIGN KEY (supplier_id) REFERENCES suppliers (id),
    CONSTRAINT fk_grn_order FOREIGN KEY (order_id) REFERENCES purchase_orders (id),
    CONSTRAINT fk_grn_wh FOREIGN KEY (warehouse_id) REFERENCES warehouses (id),
    CONSTRAINT fk_grn_journal FOREIGN KEY (journal_id) REFERENCES journal_entries (id),
    CONSTRAINT ck_grn_status CHECK (status IN ('POSTED', 'VOID'))
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_unicode_ci;

CREATE TABLE goods_receipt_lines (
    id              BIGINT         NOT NULL AUTO_INCREMENT,
    receipt_id      BIGINT         NOT NULL,
    line_no         SMALLINT       NOT NULL,
    order_line_id   BIGINT,
    item_id         BIGINT         NOT NULL,
    qty             DECIMAL(19, 4) NOT NULL,
    unit_price      DECIMAL(19, 4) NOT NULL,
    freight_alloc   DECIMAL(19, 2) NOT NULL DEFAULT 0,
    unit_cost       DECIMAL(19, 4) NOT NULL,
    total_cost      DECIMAL(19, 2) NOT NULL,
    qty_invoiced    DECIMAL(19, 4) NOT NULL DEFAULT 0,
    qty_returned    DECIMAL(19, 4) NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    KEY ix_grnl_open (item_id),
    CONSTRAINT fk_grnl_header FOREIGN KEY (receipt_id) REFERENCES goods_receipts (id) ON DELETE CASCADE,
    CONSTRAINT fk_grnl_po_line FOREIGN KEY (order_line_id) REFERENCES purchase_order_lines (id),
    CONSTRAINT fk_grnl_item FOREIGN KEY (item_id) REFERENCES items (id),
    CONSTRAINT ck_grnl_qty CHECK (qty > 0 AND qty_invoiced >= 0 AND qty_returned >= 0 AND qty_invoiced + qty_returned <= qty)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_unicode_ci;

CREATE TABLE purchase_invoices (
    id                  BIGINT         NOT NULL AUTO_INCREMENT,
    doc_no              VARCHAR(30)    NOT NULL,
    doc_date            DATE           NOT NULL,
    due_date            DATE           NOT NULL,
    supplier_id         BIGINT         NOT NULL,
    supplier_invoice_no VARCHAR(50)    NOT NULL,
    tax_invoice_no      VARCHAR(50),
    tax_rate_id         BIGINT,
    tax_rate            DECIMAL(7, 4)  NOT NULL DEFAULT 0,
    pph_rate_id         BIGINT,
    pph_rate            DECIMAL(7, 4)  NOT NULL DEFAULT 0,
    subtotal            DECIMAL(19, 2) NOT NULL DEFAULT 0,
    discount_amount     DECIMAL(19, 2) NOT NULL DEFAULT 0,
    freight_amount      DECIMAL(19, 2) NOT NULL DEFAULT 0,
    dpp                 DECIMAL(19, 2) NOT NULL DEFAULT 0,
    tax_amount          DECIMAL(19, 2) NOT NULL DEFAULT 0,
    pph_amount          DECIMAL(19, 2) NOT NULL DEFAULT 0,
    total               DECIMAL(19, 2) NOT NULL DEFAULT 0,
    payable_amount      DECIMAL(19, 2) NOT NULL DEFAULT 0,
    paid_amount         DECIMAL(19, 2) NOT NULL DEFAULT 0,
    returned_amount     DECIMAL(19, 2) NOT NULL DEFAULT 0,
    notes               VARCHAR(500),
    status              VARCHAR(12)    NOT NULL,
    journal_id          BIGINT,
    created_at          DATETIME(6)    NOT NULL,
    created_by          VARCHAR(100),
    updated_at          DATETIME(6),
    updated_by          VARCHAR(100),
    version             BIGINT         NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    UNIQUE KEY uk_pi_no (doc_no),
    UNIQUE KEY uk_pi_supplier_inv (supplier_id, supplier_invoice_no),
    KEY ix_pi_due (status, due_date),
    CONSTRAINT fk_pi_supplier FOREIGN KEY (supplier_id) REFERENCES suppliers (id),
    CONSTRAINT fk_pi_tax FOREIGN KEY (tax_rate_id) REFERENCES tax_rates (id),
    CONSTRAINT fk_pi_pph FOREIGN KEY (pph_rate_id) REFERENCES tax_rates (id),
    CONSTRAINT fk_pi_journal FOREIGN KEY (journal_id) REFERENCES journal_entries (id),
    CONSTRAINT ck_pi_status CHECK (status IN ('UNPAID', 'PARTIAL', 'PAID', 'VOID')),
    CONSTRAINT ck_pi_paid CHECK (paid_amount >= 0 AND paid_amount + returned_amount <= payable_amount)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_unicode_ci;

CREATE TABLE purchase_invoice_lines (
    id                  BIGINT         NOT NULL AUTO_INCREMENT,
    invoice_id          BIGINT         NOT NULL,
    line_no             SMALLINT       NOT NULL,
    receipt_line_id     BIGINT,
    item_id             BIGINT,
    account_id          BIGINT,
    department_id       BIGINT,
    description         VARCHAR(255)   NOT NULL,
    qty                 DECIMAL(19, 4) NOT NULL,
    unit_price          DECIMAL(19, 4) NOT NULL,
    line_total          DECIMAL(19, 2) NOT NULL,
    receipt_cost        DECIMAL(19, 2) NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    CONSTRAINT fk_pil_header FOREIGN KEY (invoice_id) REFERENCES purchase_invoices (id) ON DELETE CASCADE,
    CONSTRAINT fk_pil_grn_line FOREIGN KEY (receipt_line_id) REFERENCES goods_receipt_lines (id),
    CONSTRAINT fk_pil_item FOREIGN KEY (item_id) REFERENCES items (id),
    CONSTRAINT fk_pil_account FOREIGN KEY (account_id) REFERENCES accounts (id),
    CONSTRAINT fk_pil_dept FOREIGN KEY (department_id) REFERENCES departments (id),
    CONSTRAINT ck_pil_target CHECK (receipt_line_id IS NOT NULL OR account_id IS NOT NULL),
    CONSTRAINT ck_pil_qty CHECK (qty > 0 AND unit_price >= 0)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_unicode_ci;

