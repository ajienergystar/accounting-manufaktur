-- Pembayaran utang & uang muka pembelian
CREATE TABLE ap_payments (
    id              BIGINT         NOT NULL AUTO_INCREMENT,
    doc_no          VARCHAR(30)    NOT NULL,
    doc_date        DATE           NOT NULL,
    supplier_id     BIGINT         NOT NULL,
    payment_type    VARCHAR(20)    NOT NULL,
    cash_account_id BIGINT,
    amount          DECIMAL(19, 2) NOT NULL,
    bank_charges    DECIMAL(19, 2) NOT NULL DEFAULT 0,
    reference_no    VARCHAR(50),
    notes           VARCHAR(500),
    status          VARCHAR(10)    NOT NULL,
    journal_id      BIGINT,
    created_at      DATETIME(6)    NOT NULL,
    created_by      VARCHAR(100),
    updated_at      DATETIME(6),
    updated_by      VARCHAR(100),
    version         BIGINT         NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    UNIQUE KEY uk_app_no (doc_no),
    KEY ix_app_supplier (supplier_id),
    CONSTRAINT fk_app_supplier FOREIGN KEY (supplier_id) REFERENCES suppliers (id),
    CONSTRAINT fk_app_cash FOREIGN KEY (cash_account_id) REFERENCES accounts (id),
    CONSTRAINT fk_app_journal FOREIGN KEY (journal_id) REFERENCES journal_entries (id),
    CONSTRAINT ck_app_type CHECK (payment_type IN ('INVOICE', 'ADVANCE', 'ADVANCE_OFFSET')),
    CONSTRAINT ck_app_amount CHECK (amount > 0 AND bank_charges >= 0),
    CONSTRAINT ck_app_status CHECK (status IN ('POSTED', 'VOID'))
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_unicode_ci;

CREATE TABLE ap_payment_allocations (
    id              BIGINT         NOT NULL AUTO_INCREMENT,
    payment_id      BIGINT         NOT NULL,
    invoice_id      BIGINT         NOT NULL,
    amount          DECIMAL(19, 2) NOT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uk_apa (payment_id, invoice_id),
    CONSTRAINT fk_apa_payment FOREIGN KEY (payment_id) REFERENCES ap_payments (id) ON DELETE CASCADE,
    CONSTRAINT fk_apa_invoice FOREIGN KEY (invoice_id) REFERENCES purchase_invoices (id),
    CONSTRAINT ck_apa_amount CHECK (amount > 0)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_unicode_ci;

